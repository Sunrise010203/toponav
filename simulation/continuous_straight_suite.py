KINDS={'normal','obstacle_stop','fault_stop','no_motion','cancel_stop'}


SAFETY_MODES=('straight','l','t','route')
SAFETY_CAMERA_KINDS=('missing','silence','replay','stale','future','out_of_order','occlusion','blank')


def safety_case_arguments(case):
    """Resolve explicit runner defaults; fixture setup is NEVER controller input."""
    import inspect
    args=inspect.signature(run_case).bind_partial(None,**case['arguments']);args.apply_defaults()
    values=dict(args.arguments);values.pop('output')
    if values['scene'] is not None:values['scene']=CorridorConfig(**values['scene'])
    return values


def load_safety_suite(path):
    """S6 dry schema, coverage and denominator validation; never builds a world."""
    import re,math
    from simulation.topology import validate_pair,cardinal_heading
    from simulation.path_planning import plan_from_estimate
    suite=json.loads(Path(path).read_text())
    if not isinstance(suite,dict) or set(suite)!={'version','status','scope','cases'} or suite['version']!='continuous_safety_s6_v1' or suite['status']!='FROZEN_FOR_FIRST_GENERATION':raise ValueError('Invalid S6 suite envelope')
    cases=suite['cases'];ids=set();seeds=set();groups=Counter()
    expected=dict(normal=8,camera=32,input_error=4,cancel=4,no_prior=4,texture_boundary=4,uniform_boundary=4,blocked=2,transport=4,duplicate=1)
    if not isinstance(cases,list) or len(cases)!=sum(expected.values()):raise ValueError('Exactly67 S6 cases required')
    for c in cases:
        if not isinstance(c,dict) or set(c)!={'id','mode','expectation','arguments'}:raise ValueError('Unexpected S6 case fields')
        if not isinstance(c['id'],str) or not re.fullmatch('[a-z0-9_-]{1,80}',c['id']) or c['id'] in ids:raise ValueError('Invalid/duplicate S6 ID')
        ids.add(c['id']);mode=c['mode'];kind=c['expectation'];groups[kind]+=1
        if mode not in SAFETY_MODES or kind not in expected:raise ValueError('Invalid S6 mode or expectation')
        if not isinstance(c['arguments'],dict):raise ValueError('Expected runner arguments')
        try:a=safety_case_arguments(c)
        except (TypeError,ValueError) as error:raise ValueError('Invalid S6 runner arguments') from error
        if type(a['seed']) is not int or not 0<=a['seed']<2**31 or a['seed'] in seeds:raise ValueError('Invalid/duplicate S6 seed')
        seeds.add(a['seed'])
        if a['terminal_check_ticks']!=3 or type(a['terminal_check_ticks']) is not int:raise ValueError('Three real good frames must test terminal latch')
        if type(a['operator_confirmed']) is not bool or a['operator_confirmed'] is (kind=='no_prior'):raise ValueError('Invalid explicit initial clearance')
        if a['appearance'] is not None or a['layout_direction'] is not None:raise ValueError('Undeclared S6 appearance/layout override')
        if type(a['narrow_obstacle_width_m']) not in (int,float) or not math.isfinite(a['narrow_obstacle_width_m']) or a['narrow_obstacle_width_m']!=.5:raise ValueError('Undeclared S6 narrow blocker width')
        if a['pattern']!=('repeated' if kind=='texture_boundary' else 'uniform' if kind=='uniform_boundary' else 'unique'):raise ValueError('Changed texture boundary setup')
        if a['transport_fault'] is not None and kind not in ('transport','duplicate'):raise ValueError('Unexpected transport injection')
        if mode=='route':
            if a['route_graph'] is None or a['route_scene'] is None or a['scene'] is not None or a['corner_direction'] is not None:raise ValueError('Invalid route setup')
            validate_pair(a['route_graph'],a['route_scene'])
            if a['junction']!='l' or a['corner_geometry'] is not None:raise ValueError('Mixed route and junction arguments')
            task=a['route_graph'].get('task',{})
            start=task.get('start_node') if a['start_node'] is None else a['start_node'];goal=task.get('goal_node') if a['goal_node'] is None else a['goal_node']
            cardinal_heading(task.get('initial_heading_deg') if a['heading_deg'] is None else a['heading_deg'])
            route=plan_from_estimate(a['route_graph'],dict(status='localized',node_id=start),goal)
            if route['status']!='reachable' or route['hop_count']<2:raise ValueError('At least two route edges required')
            if a['physical_start_node'] is not None or a['physical_heading_deg'] is not None:raise ValueError('No hidden S6 spawn override')
        elif a['route_graph'] is not None or a['route_scene'] is not None or any(a[k] is not None for k in ('start_node','goal_node','heading_deg','physical_start_node','physical_heading_deg')):raise ValueError('Mixed route and primitive setup')
        if mode=='straight':
            if a['corner_direction'] is not None or a['corner_geometry'] is not None or a['junction']!='l':raise ValueError('Invalid straight setup')
        elif mode in ('l','t'):
            if a['corner_direction'] not in ('left','right') or a['junction']!=mode or a['scene'] is not None:raise ValueError('Invalid corner/junction setup')
            g=a['corner_geometry']
            if not isinstance(g,dict) or set(g)!={'width_m','corner_x_m','exit_length_m'} or any(type(v) not in (int,float) or not math.isfinite(v) for v in g.values()) or not 1.6<=g['width_m']<=2.2 or not 2.<=g['corner_x_m']<=4. or not 2.8<=g['exit_length_m']<=5.:raise ValueError('Invalid S6 corner geometry')
        f=a['fault']
        if kind in ('camera','input_error'):
            kinds=SAFETY_CAMERA_KINDS if kind=='camera' else ('bad_envelope',)
            if not isinstance(f,dict) or set(f)!={'kind','tick'} or f['kind'] not in kinds or type(f['tick']) is not int or f['tick']!=(15 if mode=='straight' else 180 if mode in ('l','t') else 700):raise ValueError('Invalid partial-motion S6 fault')
        elif f is not None:raise ValueError('Unexpected fault')
        budget=10 if kind=='no_prior' else (15 if mode=='straight' else 180 if mode in ('l','t') else 700) if kind=='cancel' else 2100 if mode=='route' else 650
        if type(a['max_ticks']) is not int or a['max_ticks']!=budget:raise ValueError('Changed S6 budget')
        if kind=='blocked':
            if mode not in ('straight','t'):raise ValueError('Unexpected blocker mode')
            if mode=='straight' and (a['scene'] is None or a['scene'].obstacle!='full_width'):raise ValueError('Missing straight physical barrier')
            if mode=='t' and a['blocked_branch']!=a['corner_direction']:raise ValueError('Missing selected branch blocker')
        elif a['blocked_branch'] is not None or (a['scene'] is not None and a['scene'].obstacle!='none'):raise ValueError('Unexpected blocker')
        if a['clear_blocker_tick'] is not None:raise ValueError('No undeclared scene mutation')
        if kind in ('transport','duplicate'):
            t=a['transport_fault']
            if mode!='route' or not isinstance(t,dict) or set(t)!={'kind','segment'} or type(t['segment']) is not int or t['segment']!=2 or t['kind'] not in (('duplicate',) if kind=='duplicate' else ('drop','stale','unknown_command','conflict')):raise ValueError('Invalid S6 second-segment transport setup')
    if dict(groups)!=expected:raise ValueError('Changed S6 denominators')
    for mode in SAFETY_MODES:
        family=[c for c in cases if c['mode']==mode]
        if sum(c['expectation']=='normal' for c in family)!=2:raise ValueError('Two functional anchors per mode required')
        if {c['arguments']['fault']['kind'] for c in family if c['expectation']=='camera'}!=set(SAFETY_CAMERA_KINDS):raise ValueError('Every mode needs all eight camera failure modes')
        for kind in ('input_error','cancel','no_prior','texture_boundary','uniform_boundary'):
            if sum(c['expectation']==kind for c in family)!=1:raise ValueError('Missing cross-mode S6 coverage')
    if {c['arguments']['transport_fault']['kind'] for c in cases if c['expectation']=='transport'}!={'drop','stale','unknown_command','conflict'}:raise ValueError('Missing transport fault')
    return suite


def run_safety_suite(suite_path,freeze,output):
    """One frozen first-generation S6 batch. No partial-result tuning."""
    suite_path=Path(suite_path).resolve();suite=load_safety_suite(suite_path);lock=verify_freeze(freeze);out=Path(output)
    if not lock.get('frozen_before_generation') or str(suite_path.relative_to(ROOT)) not in lock['files']:raise ValueError('Bound S6 freeze required before generation')
    if out.exists():raise FileExistsError('Fresh S6 output required')
    digest=hashlib.sha256(suite_path.read_bytes()).hexdigest()
    _write(Path(freeze).parent/'FIRST_S6_GENERATION_STARTED.json',dict(started_at=datetime.now(timezone.utc).isoformat(),output=str(out.resolve()),suite_sha256=digest))
    out.mkdir(parents=True,exist_ok=False);completed=[]
    _write(out/'environment.json',dict(python=sys.version,executable=sys.executable,platform=platform.platform(),clock_domain='synchronous simulation; NOT real-time hardware watchdog'))
    for c in suite['cases']:
        verify_freeze(freeze);run_case(out/c['id'],**safety_case_arguments(c))
        completed.append(c['id']);(out/'partial-progress.json').write_text(json.dumps(dict(cases=completed),indent=2)+'\n')
        print('S6_CASE_COMPLETE',c['id'],flush=True)
    verify_freeze(freeze)
    _write(out/'phase-complete.json',dict(method='S6_control',cases=completed,suite_sha256=digest))


def load_route_suite(path):
    """S5 prospective validation. No world, reference, RGB or pose generation."""
    import re
    from simulation.topology import validate_pair,cardinal_heading
    from simulation.path_planning import plan_from_estimate
    suite=json.loads(Path(path).read_text())
    if set(suite)!={'version','status','scope','cases'} or suite['version']!='continuous_route_s5_v1' or suite['status']!='FROZEN_FOR_FIRST_GENERATION':raise ValueError('Invalid S5 suite envelope')
    cases=suite['cases'];fields={'id','seed','expectation','layout','graph','physical_scene','start_node','goal_node','heading_deg','physical_start_node','physical_heading_deg','max_ticks','operator_confirmed','fault','transport_fault'}
    if not isinstance(cases,list) or len(cases)!=24:raise ValueError('Exactly24 predeclared S5 cases required')
    groups=Counter();ids=set();seeds=set();layouts={}
    for c in cases:
        if not isinstance(c,dict) or set(c)!=fields:raise ValueError('Unexpected S5 case fields')
        if not isinstance(c['id'],str) or not re.fullmatch('[a-z0-9_-]{1,80}',c['id']) or c['id'] in ids:raise ValueError('Invalid/duplicate route case ID')
        if type(c['seed']) is not int or not 0<=c['seed']<2**31 or c['seed'] in seeds:raise ValueError('Invalid/duplicate route seed')
        ids.add(c['id']);seeds.add(c['seed']);groups[c['expectation']]+=1
        validate_pair(c['graph'],c['physical_scene']);cardinal_heading(c['heading_deg']);cardinal_heading(c['physical_heading_deg'])
        node_ids={n['node_id'] for n in c['graph']['nodes']}
        if c['physical_start_node'] not in node_ids:raise ValueError('Invalid physical start')
        route=plan_from_estimate(c['graph'],dict(status='localized',node_id=c['start_node']),c['goal_node'])
        if route['status']!='reachable' or route['hop_count']<2:raise ValueError('Every route must require at least two edges')
        if type(c['operator_confirmed']) is not bool or c['operator_confirmed'] is (c['expectation']=='no_prior'):raise ValueError('Invalid S5 clearance prior')
        if type(c['max_ticks']) is not int or c['max_ticks'] not in ((180,700) if c['expectation']=='cancel' else (10,) if c['expectation']=='no_prior' else (2100,)):raise ValueError('Invalid declared S5 budget')
        kind=c['expectation'];f=c['fault'];t=c['transport_fault']
        if kind=='camera':
            if not isinstance(f,dict) or set(f)!={'kind','tick'} or f['kind'] not in ('missing','replay','stale','occlusion') or type(f['tick']) is not int or f['tick'] not in (180,700):raise ValueError('Invalid partial-route camera fault')
        elif f is not None:raise ValueError('Unexpected camera injection')
        if kind in ('duplicate','transport'):
            if not isinstance(t,dict) or set(t)!={'kind','segment'} or t['segment']!=2 or type(t['segment']) is not int or t['kind'] not in (('duplicate',) if kind=='duplicate' else ('drop','stale','unknown_command','conflict')):raise ValueError('Invalid route feedback injection')
        elif t is not None:raise ValueError('Unexpected route feedback injection')
        if kind!='wrong_start' and c['physical_start_node']!=c['start_node']:raise ValueError('Undeclared wrong start')
        if kind not in ('wrong_start','wrong_heading') and c['physical_heading_deg']!=c['heading_deg']:raise ValueError('Undeclared wrong heading')
        if kind=='wrong_start' and c['physical_start_node']==c['start_node']:raise ValueError('Wrong start not exercised')
        if kind=='wrong_heading' and c['physical_heading_deg']==c['heading_deg']:raise ValueError('Wrong heading not exercised')
        if kind=='normal':
            scene=json.dumps(c['physical_scene'],sort_keys=True)
            if c['layout'] in layouts and layouts[c['layout']]!=scene:raise ValueError('A named layout changed geometry')
            layouts[c['layout']]=scene
    expected=dict(normal=6,duplicate=2,camera=4,wrong_start=2,wrong_heading=2,transport=4,cancel=2,no_prior=2)
    if dict(groups)!=expected:raise ValueError('Changed S5 separate denominators')
    if len(layouts)!=2 or len(set(layouts.values()))!=2:raise ValueError('Two independent normal physical layouts required')
    for layout in layouts:
        family=[c for c in cases if c['expectation']=='normal' and c['layout']==layout]
        if len(family)!=3 or len({(c['start_node'],c['goal_node']) for c in family})!=3:raise ValueError('Three distinct tasks per layout required')
    if {c['fault']['kind'] for c in cases if c['expectation']=='camera'}!={'missing','replay','stale','occlusion'}:raise ValueError('Missing camera failure mode')
    if {c['transport_fault']['kind'] for c in cases if c['expectation']=='transport'}!={'drop','stale','unknown_command','conflict'}:raise ValueError('Missing transport failure mode')
    return suite


