def load_suite(path):
    suite=json.loads(Path(path).read_text())
    if not isinstance(suite,dict) or set(suite)!={'version','status','scope','normal_minimum_fraction','cases'}:raise ValueError('Invalid S2 suite envelope')
    if suite['version'] not in ('continuous_straight_s2_v1_candidate','continuous_straight_s2_v1') or suite['normal_minimum_fraction']!=.8:raise ValueError('Unsupported suite or changed gate')
    if suite['status'] not in ('PROSPECTIVE_UNFROZEN_NOT_GENERATED','FROZEN_FOR_FIRST_GENERATION'):raise ValueError('Invalid suite lifecycle')
    cases=suite['cases']
    if not isinstance(cases,list) or len(cases)!=20:raise ValueError('Exactly20 predeclared cases required')
    required={'id','seed','expectation','scene','appearance','pattern','max_ticks','operator_confirmed','tags','fault'}
    ids=set();seeds=set();groups=Counter()
    for c in cases:
        if not isinstance(c,dict) or not required<=set(c) or set(c)-required-{'narrow_obstacle_width_m'}:raise ValueError('Only declared setup/task fields allowed')
        validate_case(dict(id=c['id'],group='anchor',scene=c['scene'],appearance=c['appearance']))
        if c['id'] in ids or type(c['seed']) is not int or not 0<=c['seed']<2**31 or c['seed'] in seeds:raise ValueError('Duplicate ID/seed or invalid seed')
        ids.add(c['id']);seeds.add(c['seed'])
        if c['expectation'] not in KINDS or c['pattern'] not in ('unique','repeated','uniform'):raise ValueError('Invalid expectation/pattern')
        if type(c['operator_confirmed']) is not bool or type(c['max_ticks']) is not int or not 1<=c['max_ticks']<=600:raise ValueError('Invalid operational prior/budget')
        if not isinstance(c['tags'],list) or any(t not in {'offset','yaw','material','lighting','paint'} for t in c['tags']):raise ValueError('Invalid family tags')
        width=c.get('narrow_obstacle_width_m',.5)
        if type(width) not in (int,float) or not .25<=width<=.5:raise ValueError('Invalid narrow width')
        fault=c['fault'];kind=c['expectation'];scene=CorridorConfig(**c['scene'])
        if kind=='fault_stop':
            if not isinstance(fault,dict) or set(fault)!={'kind','tick'} or fault['kind'] not in {'missing','replay','stale','occlusion'} or type(fault['tick']) is not int or not 20<=fault['tick']<c['max_ticks']:raise ValueError('Unreachable or unsupported late fault')
        elif fault is not None:raise ValueError('Unexpected fault outside its denominator')
        if kind=='normal' and (not c['operator_confirmed'] or c['pattern']!='unique' or scene.obstacle!='none'):raise ValueError('Safety rejection cannot be recast as normal success')
        if kind=='no_motion' and c['operator_confirmed'] and c['pattern']=='unique':raise ValueError('No-motion counterexample lacks a declared cause')
        if kind=='obstacle_stop' and scene.obstacle=='none':raise ValueError('Missing physical blocker')
        if kind=='cancel_stop' and (not c['operator_confirmed'] or c['max_ticks']!=12):raise ValueError('Invalid finite-budget partial-motion case')
        groups[kind]+=1
    if dict(groups)!=dict(normal=10,obstacle_stop=2,fault_stop=4,no_motion=3,cancel_stop=1):raise ValueError('Changed outcome denominators')
    return suite


def _write(path,value):
    with Path(path).open('x') as f:json.dump(value,f,indent=2,allow_nan=False)


def run_suite(suite_path,freeze,output):
    suite_path=Path(suite_path).resolve();lock=verify_freeze(freeze);suite=load_suite(suite_path)
    relative=str(suite_path.relative_to(ROOT))
    if relative not in lock['files'] or not lock.get('frozen_before_generation') or suite['status']!='FROZEN_FOR_FIRST_GENERATION':raise ValueError('Bound source/suite freeze required BEFORE generation')
    # One receipt per candidate. Interrupted attempts remain visible, not
    # silently restarted into an apparently untouched successful run.
    receipt=Path(freeze).parent/'FIRST_S2_GENERATION_STARTED.json'
    if Path(output).exists():raise FileExistsError('Fresh output required; never overwrite an earlier attempt')
    _write(receipt,dict(started_at=datetime.now(timezone.utc).isoformat(),output=str(Path(output).resolve()),suite_sha256=hashlib.sha256(suite_path.read_bytes()).hexdigest()))
    out=Path(output);out.mkdir(parents=True,exist_ok=False)
    _write(out/'environment.json',dict(python=sys.version,executable=sys.executable,platform=platform.platform(),clock_domain='synchronous simulation seconds, paused during computation; not wall-clock realtime',freeze=str(Path(freeze).resolve())))
    completed=[]
    for c in suite['cases']:
        verify_freeze(freeze)
        r=run_case(out/c['id'],scene=CorridorConfig(**c['scene']),appearance=c['appearance'],seed=c['seed'],pattern=c['pattern'],max_ticks=c['max_ticks'],operator_confirmed=c['operator_confirmed'],fault=c['fault'],narrow_obstacle_width_m=c.get('narrow_obstacle_width_m',.5))
        completed.append(c['id']);(out/'partial-progress.json').write_text(json.dumps(dict(cases=completed),indent=2)+'\n')
        print('S2_PRIMARY_COMPLETE',c['id'],r['controller_result']['result_type'],flush=True)
    verify_freeze(freeze)
    _write(out/'phase-complete.json',dict(method='S2_control',cases=completed,suite_sha256=hashlib.sha256(suite_path.read_bytes()).hexdigest()))


