def load_junction_suite(path):
    """S4 setup validation only: never renders an image or reads a pose."""
    import math
    import re
    suite=json.loads(Path(path).read_text())
    if set(suite)!={'version','status','scope','cases'} or suite['version']!='t_junction_s4_v1' or suite['status']!='FROZEN_FOR_FIRST_GENERATION':raise ValueError('Invalid S4 suite envelope')
    cases=suite['cases']
    if not isinstance(cases,list) or len(cases)!=26:raise ValueError('Exactly26 predeclared S4 cases required')
    fields={'id','seed','expectation','direction','layout','geometry','max_ticks','operator_confirmed','fault','blocked_branch','clear_blocker_tick'}
    ids=set();seeds=set();groups=Counter()
    for c in cases:
        if not isinstance(c,dict) or set(c)!=fields:raise ValueError('Unexpected S4 setup fields')
        if not isinstance(c['id'],str) or not re.fullmatch('[a-z0-9_-]{1,80}',c['id']) or c['id'] in ids:raise ValueError('Invalid/duplicate S4 ID')
        if type(c['seed']) is not int or not 0<=c['seed']<2**31 or c['seed'] in seeds:raise ValueError('Invalid/duplicate S4 seed')
        ids.add(c['id']);seeds.add(c['seed'])
        if c['direction'] not in ('left','right') or c['layout'] not in ('base','wide','safety'):raise ValueError('Invalid S4 direction/layout')
        if type(c['operator_confirmed']) is not bool or type(c['max_ticks']) is not int or not 1<=c['max_ticks']<=650:raise ValueError('Invalid S4 prior/budget')
        g=c['geometry'];ranges={'width_m':(1.6,2.2),'corner_x_m':(2.,4.),'exit_length_m':(2.8,5.)}
        if not isinstance(g,dict) or set(g)!=set(ranges) or any(type(g[k]) not in (int,float) or not math.isfinite(g[k]) or not low<=g[k]<=high for k,(low,high) in ranges.items()):raise ValueError('Invalid T fixture geometry')
        kind=c['expectation'];groups[kind]+=1
        if kind=='fault_stop':
            f=c['fault']
            if not isinstance(f,dict) or set(f)!={'kind','tick'} or f['kind'] not in ('missing','replay','stale','occlusion') or type(f['tick']) is not int or not 20<=f['tick']<c['max_ticks']:raise ValueError('Invalid midturn fault')
        elif c['fault'] is not None:raise ValueError('Fault outside fault denominator')
        blocked=c['blocked_branch'];clear=c['clear_blocker_tick']
        if blocked not in (None,'left','right'):raise ValueError('Invalid branch blocker')
        if kind in ('blocked','clear_after_wait'):
            if blocked!=c['direction']:raise ValueError('Selected branch blocker required')
        elif kind=='alternative_blocked':
            if blocked is None or blocked==c['direction']:raise ValueError('Unselected branch blocker required')
        elif blocked is not None:raise ValueError('Unexpected blocker')
        if kind=='clear_after_wait':
            if type(clear) is not int or not 20<=clear<c['max_ticks']-3:raise ValueError('Invalid temporary blocker removal')
        elif clear is not None:raise ValueError('Unexpected fixture clearing event')
        if c['operator_confirmed'] is (kind=='no_motion'):raise ValueError('Inconsistent initial clearance prior')
        if c['max_ticks']!=(12 if kind=='cancel_stop' else 650):raise ValueError('Changed S4 budget')
    if dict(groups)!=dict(normal=8,fault_stop=8,blocked=2,clear_after_wait=2,alternative_blocked=2,no_motion=2,cancel_stop=2):raise ValueError('Changed S4 denominators')
    for direction in ('left','right'):
        for layout in ('base','wide'):
            family=[c for c in cases if c['expectation']=='normal' and c['direction']==direction and c['layout']==layout]
            if len(family)!=2 or len({tuple(sorted(c['geometry'].items())) for c in family})!=1:raise ValueError('Missing direction/layout replicates')
        for kind in ('blocked','clear_after_wait','alternative_blocked','no_motion','cancel_stop'):
            if sum(c['expectation']==kind and c['direction']==direction for c in cases)!=1:raise ValueError('Missing bidirectional safety/functional coverage')
        if {c['fault']['kind'] for c in cases if c['expectation']=='fault_stop' and c['direction']==direction}!={'missing','replay','stale','occlusion'}:raise ValueError('Missing fault-direction coverage')
    layouts={tuple(sorted(c['geometry'].items())) for c in cases if c['expectation']=='normal'}
    if len(layouts)!=2:raise ValueError('Two distinct normal T layouts required')
    return suite


